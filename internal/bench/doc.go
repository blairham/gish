package bench

import (
	"fmt"
	"runtime"
	"strings"
	"time"
)

// Report renders docs/bench.md (#102): the startup table, the
// keystroke percentiles, and the methodology that makes both
// arguable. Machine details are printed because a benchmark without
// them is a rumor.
func Report(startups []StartupResult, keystrokes []KeystrokeResult, runs, samples int) string {
	var b strings.Builder

	b.WriteString("# benchmarks\n\n")
	b.WriteString("*Generated by `make bench` from `internal/bench` — do not edit by hand.*\n\n")
	fmt.Fprintf(&b, "Measured on %s/%s, %d CPUs, Go %s, %s.\n\n",
		runtime.GOOS, runtime.GOARCH, runtime.NumCPU(), runtime.Version(),
		time.Now().Format("2006-01-02"))

	b.WriteString(`## Time to first prompt

Every shell is launched under a real pty with a temp rc that sets its
prompt to the same marker, so "first prompt" is one comparable event.
Each row is the median of ` + itoa(runs) + ` runs, with the fastest run beside it —
both, because quoting only your best number is how benchmarks lie.

| configuration | median | best | what it includes |
| --- | ---: | ---: | --- |
`)
	for _, r := range startups {
		if !r.Available {
			fmt.Fprintf(&b, "| %s | — | — | *%s* |\n", r.Label, r.Note)
			continue
		}
		if r.Err != "" {
			fmt.Fprintf(&b, "| %s | error | — | %s (%s) |\n", r.Label, r.Note, r.Err)
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n",
			r.Label, ms(r.Median()), ms(r.Best()), r.Note)
	}

	b.WriteString(`
### What the loaded-config row means

The empty-config rows are floors nobody runs. The row that matters is
the loaded one: a real .zshrc with a plugin manager, a theme, and tool
init hooks against koi with its theme, highlighting, suggestions, and
lint all on — because that is the comparison a switcher actually
experiences. koi's features are compiled in rather than sourced, so
turning them on costs approximately nothing at startup; the zsh
equivalent pays for each one at every prompt.

## Keystroke latency

The question every "out-of-process plugins" thread asks is whether
there is RPC in the keystroke path. This measures end to end: a byte
goes into the pty and the clock stops when the repaint comes back out,
so decode, buffer edit, highlighting, suggestion lookup, lint, and
render are all inside the number. Nothing is instrumented in-process —
what the terminal sees is the honest measurement.

`)
	fmt.Fprintf(&b, "%d samples per scenario.\n\n", samples)
	b.WriteString("| scenario | p50 | p99 | what is active |\n| --- | ---: | ---: | --- |\n")
	for _, k := range keystrokes {
		if k.Err != "" {
			fmt.Fprintf(&b, "| %s | error | — | %s (%s) |\n", k.Scenario, k.Note, k.Err)
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", k.Scenario, ms(k.P50()), ms(k.P99()), k.Note)
	}

	b.WriteString(`
## Methodology and honesty notes

- **One machine, one moment.** These numbers describe the machine in
  the header, not your laptop and not a CI runner. Rerun ` + "`make bench`" + `
  to get yours; the harness is the point, the table is a sample.
- **Same event everywhere.** Each shell's prompt is overridden to a
  shared marker, so no shell is credited for a prompt that renders
  faster because it says less.
- **Not-installed is printed, not hidden.** A shell missing from this
  machine gets a row saying so rather than quietly vanishing from the
  comparison.
- **Empty-config rows are floors, not experiences.** "zsh (no rc)" is
  not what anyone runs; the loaded-config row exists because that is
  the number people actually feel. Compare like with like.
- **Keystroke latency includes the render.** A shell that decodes fast
  and paints slowly is slow, and this measurement says so.
- **Differences under about a millisecond are noise.** Process spawn
  and pty setup dominate at this scale, which is why the koi rows sit
  within noise of each other regardless of features enabled — the
  features are not on the startup path. Do not read a ranking into
  sub-millisecond gaps.
- **What is not measured here**: throughput of script execution
  (see ` + "`docs/compat.md`" + ` for correctness), memory, and plugin-heavy
  keystroke paths — the plugin scenarios need a plugin set installed,
  which the harness will grow once there is one worth publishing.
`)
	return b.String()
}

// ms renders a duration in milliseconds with one decimal — the unit
// this argument is conducted in.
func ms(d time.Duration) string {
	return fmt.Sprintf("%.1f ms", float64(d.Microseconds())/1000)
}

func itoa(n int) string { return fmt.Sprintf("%d", n) }
